-- Export dimostrativo dello schema AURORA, compatibile con il parser DDL minimale.
-- I dati e i nomi sono interamente fittizi.

CREATE TABLE CLI_CLIENTE (
  ID_CLIENTE NUMBER(10) NOT NULL,
  CODICE_FISCALE VARCHAR2(16) NOT NULL,
  NOME VARCHAR2(60) NOT NULL,
  COGNOME VARCHAR2(60) NOT NULL,
  DATA_NASCITA DATE NOT NULL,
  EMAIL VARCHAR2(120),
  PRIMARY KEY (ID_CLIENTE),
  UNIQUE (CODICE_FISCALE)
);

CREATE TABLE PRT_PRATICA (
  ID_PRATICA NUMBER(10) NOT NULL,
  ID_CLIENTE NUMBER(10) NOT NULL,
  STATO VARCHAR2(20) NOT NULL,
  IMPORTO NUMBER(12,2) NOT NULL,
  DURATA_MESI NUMBER(3) NOT NULL,
  TASSO NUMBER(6,3) NOT NULL,
  DATA_RICHIESTA DATE NOT NULL,
  DATA_APPROVAZIONE DATE,
  PRIMARY KEY (ID_PRATICA),
  FOREIGN KEY (ID_CLIENTE) REFERENCES CLI_CLIENTE(ID_CLIENTE)
);

CREATE TABLE PRT_RATA (
  ID_RATA NUMBER(12) NOT NULL,
  ID_PRATICA NUMBER(10) NOT NULL,
  NUMERO_RATA NUMBER(3) NOT NULL,
  DATA_SCADENZA DATE NOT NULL,
  IMPORTO NUMBER(12,2) NOT NULL,
  STATO VARCHAR2(20) NOT NULL,
  PRIMARY KEY (ID_RATA),
  FOREIGN KEY (ID_PRATICA) REFERENCES PRT_PRATICA(ID_PRATICA),
  UNIQUE (ID_PRATICA, NUMERO_RATA)
);

CREATE TABLE PRT_PAGAMENTO (
  ID_PAGAMENTO NUMBER(12) NOT NULL,
  ID_RATA NUMBER(12) NOT NULL,
  DATA_PAGAMENTO DATE NOT NULL,
  IMPORTO NUMBER(12,2) NOT NULL,
  ESITO VARCHAR2(20) NOT NULL,
  PRIMARY KEY (ID_PAGAMENTO),
  FOREIGN KEY (ID_RATA) REFERENCES PRT_RATA(ID_RATA)
);
